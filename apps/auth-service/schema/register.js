const {mongoose}=require('@codekro/db_config');

const userSchema=new mongoose.Schema({
    name:{
        type:String,
        required:true,
        trim:true,
        maxlength:100
    },
    email:{
        type:String,
        required:true,
        unique:true,
        trim:true,
        lowercase:true
    },
    username:{
        type:String,
        required:true,
        unique:true,
        trim:true,
        lowercase:true
    },
    picture:{
        type:String,
        trim:true
    },
    bio:{
        type:String,
        default:"",
        trim:true,
        maxlength:160
    },
    location:{
        type:String,
        default:"",
        trim:true,
        maxlength:100
    },
    organization:{
        type:String,
        default:"",
        trim:true,
        maxlength:100
    },
    website:{
        type:String,
        default:"",
        trim:true,
        maxlength:200
    },
    github:{
        type:String,
        default:"",
        trim:true,
        maxlength:100
    },
    linkedin:{
        type:String,
        default:"",
        trim:true,
        maxlength:200
    },
    followers:[{
        type:mongoose.Schema.Types.ObjectId,
        ref:"CodeKroUser"
    }],
    following:[{
        type:mongoose.Schema.Types.ObjectId,
        ref:"CodeKroUser"
    }],
    password:{
        type:String,
        trim:true
    }
},{
    timestamps:true
})

module.exports=new mongoose.model('CodeKroUser',userSchema);